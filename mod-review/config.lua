local config = {}

-- 存档留多少局（超出按 seq 淘汰最旧）。见 FORMAT.md §6
config.maxRuns = 50

-- 字节预算硬线：超过就从最旧的局开始整局淘汰。
-- 参照：你机器上最大的 mod 存档是 reverie 的 291 KB；这里留到 1.2 MB 的余量。
config.maxBlobBytes = 1200000

-- 是否往 log.txt 打印采集细节（v0.1 必须开，否则什么都看不见）
config.debug = true

-- 是否在本次会话第一次进房时，把"游戏实际能给的字段"全量导出到日志
-- （道具全表 + 当前房间全字段 + 道具池探针）
config.dumpOnce = true

-- 是否记录房间里的"道具座"坐标。
-- ⚠️ 实测发现：Data.Spawns 包含的是**所有**刷怪点（怪物、掉落、家具…），
-- 不只是道具座。默认关闭，等做了"按 EntityType/Subtype 过滤"再开。
config.capturePeds = false

-- 道具采集黑名单：这些 id 永远不会被记成"本房获得"。
-- 313 = 神圣屏障（Holy Mantle）：别的 mod 会往身上反复挂这个效果，
-- 实测一局被误记 4 次，玩家根本没拿过。作者 2026-10-21 要求排除。
-- 加新条目就照格式加一行 [id] = true。
config.itemBlacklist = {
    [313] = true,
}

-- 高光判定阈值（v0.1 **不使用**，只记录；等跑出真实分布再定，见 DESIGN.md §6）
config.thresholds = {
    relPct       = 15,   -- 相对进房战力增长 ≥ 15%
    absDelta     = 0.5,  -- 绝对增长 ≥ 0.5（战力单位）
    perFloorMax  = 3,    -- 每层最多收录
    topK         = 5,    -- 本局强制收录的 Top-K
}

-- 楼层需求战力表（展示用，不参与高光判定）。v1 先占位 1.0，等手填
config.floorDemand = {
    [1] = 1.0, [2] = 1.0, [3] = 1.0, [4] = 1.0, [5] = 1.0, [6] = 1.0,
    [7] = 1.0, [8] = 1.0, [9] = 1.0, [10] = 1.0, [11] = 1.0, [12] = 1.0,
}

return config
